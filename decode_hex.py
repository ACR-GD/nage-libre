font = {}
with open('nage_libre.tbl', 'r', encoding='utf-8') as f:
    for line in f:
        if '=' in line:
            hx, ch = line.strip().split('=')
            font[int(hx, 16)] = ch

for k, arr in ptrs.items():
    text = ""
    for cid in arr:
        if cid in font: text += font[cid]
        else: text += f"[{cid:04X}]"
    print(f"{k}: {text}")
