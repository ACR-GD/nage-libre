# simple script to decode assuming hex
hex_dict = {
    0x02DE: "西", 0x01DA: "暦", 0x02C8: "神", 0x00AE: "聖", 0x0020: "記", 0x003A: "３", 0x001C: "９", 0x0058: "９", 0x0066: "８",
    0x0032: "年", 0x00A8: "地球",
    0x005A: "地", 0x009C: "球", 0x00B4: "の", 0x00CC: "滅", 0x0118: "亡", 0x00F2: "ま",
    0x00D0: "人", 0x0088: "こ", 0x0100: "れ", 0x0022: "か",
    0x001C: "の", 0x0068: "世", 0x00FC: "界", 0x0092: "を", 0x00EC: "全", 0x00AE: "て", 0x002E: "私", 0x003A: "の", 0x0088: "物", 0x003E: "に", 0x009E: "…",
}

def decode_string(words):
    return ''.join(hex_dict.get(w, f"[{w:04X}]") for w in words)

